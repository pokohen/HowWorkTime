/**
 * 모델 응답에 흔히 섞이는 아주 가벼운 마크다운만 다룬다.
 * 지원: 제목(#), 글머리(-, *, 숫자.), 번호 목록 안의 들여쓴 글머리, 구분선(---), **굵게**, `코드`, 줄바꿈. 그 외는 글자 그대로.
 * 한 번 블록으로 쪼갠 뒤 HTML(화면)과 일반 텍스트(복사)로 각각 찍어, 두 결과의 목록 번호가 늘 같다.
 * HTML 은 입력을 먼저 전부 이스케이프하므로 v-html 에 넣어도 스크립트가 끼어들 수 없다.
 */
const 이스케이프표 = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }

export function HTML이스케이프(텍스트) {
  return String(텍스트).replace(/[&<>"']/g, (c) => 이스케이프표[c])
}

/**
 * 코드 스팬 안의 기호(예: `**` 나 `*`)가 굵게 규칙에 걸리지 않도록, 코드를 먼저 떼어 두고 나머지만 바꾼 뒤 되돌린다.
 * @param {string} 텍스트
 * @param {(코드: string) => string} 코드변환
 * @param {(나머지: string) => string} 나머지변환
 */
function 코드보호(텍스트, 코드변환, 나머지변환) {
  const 코드들 = []
  // 자리표시에 NUL 을 쓰므로 입력의 NUL 은 미리 걷어낸다 (글에 의미 있는 글자가 아니다)
  const 자리 = 텍스트.replace(/\u0000/g, '').replace(/`([^`\n]+)`/g, (_, 코드) => {
    코드들.push(코드변환(코드))
    return `\u0000${코드들.length - 1}\u0000`
  })
  return 나머지변환(자리).replace(/\u0000(\d+)\u0000/g, (_, i) => 코드들[Number(i)])
}

const 인라인HTML = (텍스트) => 코드보호(
  HTML이스케이프(텍스트),
  (코드) => `<code>${코드}</code>`,
  (나머지) => 나머지.replace(/\*\*([^*\n]+)\*\*/g, '<strong>$1</strong>'),
)
const 인라인텍스트 = (텍스트) => 코드보호(텍스트, (코드) => 코드, (나머지) => 나머지.replace(/\*\*([^*\n]+)\*\*/g, '$1'))

/**
 * 줄들을 블록으로 쪼갠다.
 * @returns {Array<
 *   | { 종류: 'p', 줄들: string[] }
 *   | { 종류: 'h', 글: string }
 *   | { 종류: 'hr' }
 *   | { 종류: 'ul', 항목: Array<{ 글: string }> }
 *   | { 종류: 'ol', 시작: number, 항목: Array<{ 글: string, 하위: string[] }> }
 * >}
 */
function 블록파싱(텍스트) {
  const 줄들 = String(텍스트 ?? '').replace(/\r\n?/g, '\n').split('\n')
  const 블록들 = []
  let 목록 = null // 열려 있는 ul/ol 블록
  let 문단 = null
  // 바로 앞 번호 목록의 마지막 번호. 빈 줄이나 글머리 목록을 사이에 두고 이어지는 "2." 가 다시 1 부터 세어지지 않게.
  // 문단·제목·구분선이 끼면 끊긴다
  let 직전번호 = 0

  const 문단닫기 = () => { if (문단) { 블록들.push(문단); 문단 = null; 직전번호 = 0 } }
  const 목록닫기 = () => {
    if (!목록) return
    if (목록.종류 === 'ol') 직전번호 = 목록.시작 + 목록.항목.length - 1
    목록 = null
  }
  const 마지막항목 = () => 목록?.항목[목록.항목.length - 1]

  for (const 원줄 of 줄들) {
    const 줄 = 원줄.trimEnd()
    const 들여씀 = /^\s/.test(줄)
    const 제목 = /^#{1,6}\s+(.+)$/.exec(줄)
    const 수평선 = /^\s*([-*_])(\s*\1){2,}\s*$/.test(줄) // "---" "* * *" 같은 구분선
    const 글머리 = !수평선 && /^\s*[-*•]\s+(.+)$/.exec(줄)
    // 번호 목록은 1 로 시작하거나 번호 목록에 이어질 때만. "2026. 상반기에는…" 같은 문장을 목록으로 오해하지 않게
    const 번호후보 = /^\s*(\d{1,2})[.)]\s+(.+)$/.exec(줄)
    const 번호이어짐 = 목록?.종류 === 'ol' || (!문단 && 직전번호 > 0)
    const 번호 = 번호후보 && (번호후보[1] === '1' || 번호이어짐) ? 번호후보 : null

    if (!줄.trim()) {
      문단닫기(); 목록닫기()
    } else if (수평선) {
      문단닫기(); 목록닫기()
      블록들.push({ 종류: 'hr' }); 직전번호 = 0
    } else if (제목) {
      문단닫기(); 목록닫기()
      블록들.push({ 종류: 'h', 글: 제목[1] }); 직전번호 = 0
    } else if (글머리 && 들여씀 && 목록?.종류 === 'ol') {
      // 번호 항목 아래 들여쓴 글머리는 그 항목의 하위 목록 (일정의 "1. 첫째 날\n   - 아침 …" 꼴)
      마지막항목().하위.push(글머리[1])
    } else if (글머리 || 번호) {
      문단닫기()
      const 종류 = 글머리 ? 'ul' : 'ol'
      if (목록 && 목록.종류 !== 종류) 목록닫기()
      if (!목록) {
        // 빈 줄 뒤에 이어지는 번호는 새 목록이 되므로 앞 목록의 번호를 이어 받는다 (모델이 "1. 1. 1." 로 써도 1, 2, 3)
        목록 = 종류 === 'ol' ? { 종류, 시작: 번호이어짐 ? 직전번호 + 1 : 1, 항목: [] } : { 종류, 항목: [] }
        블록들.push(목록)
      }
      목록.항목.push(종류 === 'ol' ? { 글: 번호[2], 하위: [] } : { 글: 글머리[1] })
    } else if (목록 && 들여씀) {
      // 목록 항목 바로 아래 들여쓴 이어지는 줄은 마지막 항목(하위가 있으면 마지막 하위)에 붙인다
      const 항목 = 마지막항목()
      if (항목.하위?.length) 항목.하위[항목.하위.length - 1] += ` ${줄.trim()}`
      else 항목.글 += ` ${줄.trim()}`
    } else {
      목록닫기()
      if (!문단) { 문단 = { 종류: 'p', 줄들: [] }; 직전번호 = 0 }
      문단.줄들.push(줄)
    }
  }
  문단닫기(); 목록닫기()
  return 블록들
}

/**
 * @param {string} 텍스트
 * @returns {string} HTML
 */
export function 마크다운HTML(텍스트) {
  return 블록파싱(텍스트).map((블록) => {
    switch (블록.종류) {
      case 'p': return `<p>${블록.줄들.map(인라인HTML).join('<br>')}</p>`
      case 'h': return `<h4>${인라인HTML(블록.글)}</h4>`
      case 'hr': return '<hr>'
      case 'ul': return `<ul>${블록.항목.map((항목) => `<li>${인라인HTML(항목.글)}</li>`).join('')}</ul>`
      case 'ol': {
        const 시작 = 블록.시작 > 1 ? ` start="${블록.시작}"` : ''
        const 항목들 = 블록.항목.map((항목) => {
          const 하위 = 항목.하위.length ? `<ul>${항목.하위.map((글) => `<li>${인라인HTML(글)}</li>`).join('')}</ul>` : ''
          return `<li>${인라인HTML(항목.글)}${하위}</li>`
        })
        return `<ol${시작}>${항목들.join('')}</ol>`
      }
      default: return ''
    }
  }).join('')
}

/**
 * 공유용 일반 텍스트. 마크다운 기호를 걷어내 메신저·메모에 붙여 넣어도 깔끔하게 보인다.
 * 제목은 그대로 한 줄, 글머리는 "• ", 번호 목록은 화면과 같은 번호로, 굵게·코드는 기호만 벗긴다. 구분선은 빈 줄.
 * @param {string} 텍스트
 * @returns {string}
 */
export function 마크다운텍스트(텍스트) {
  return 블록파싱(텍스트).map((블록) => {
    switch (블록.종류) {
      case 'p': return 블록.줄들.map(인라인텍스트).join('\n')
      case 'h': return 인라인텍스트(블록.글)
      case 'hr': return ''
      case 'ul': return 블록.항목.map((항목) => `• ${인라인텍스트(항목.글)}`).join('\n')
      case 'ol': return 블록.항목.map((항목, i) => [
        `${블록.시작 + i}. ${인라인텍스트(항목.글)}`,
        ...항목.하위.map((글) => `  • ${인라인텍스트(글)}`),
      ].join('\n')).join('\n')
      default: return ''
    }
  }).filter(Boolean).join('\n\n')
}
