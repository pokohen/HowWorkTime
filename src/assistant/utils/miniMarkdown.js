/**
 * 모델 응답에 흔히 섞이는 아주 가벼운 마크다운만 다룬다.
 * 지원: 제목(#), 글머리(-, *, 숫자.), 들여쓴 하위 목록과 이어지는 줄, 빈 줄로 띄운 목록, 구분선(---),
 * 코드 블록(```), **굵게**, `코드`, 줄바꿈. 그 외는 글자 그대로.
 * 한 번 블록으로 쪼갠 뒤 HTML(화면)과 일반 텍스트(복사)로 각각 찍어, 두 결과의 목록 번호가 늘 같다.
 * HTML 은 입력을 먼저 전부 이스케이프하므로 v-html 에 넣어도 스크립트가 끼어들 수 없다.
 */
const 이스케이프표 = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }

export function HTML이스케이프(텍스트) {
  return String(텍스트).replace(/[&<>"']/g, (c) => 이스케이프표[c])
}

/**
 * 코드 스팬 안의 기호(예: `**` 나 `*`)가 굵게 규칙에 걸리지 않도록, 코드를 먼저 떼어 두고 나머지만 바꾼 뒤 되돌린다.
 * @param {string} 텍스트
 * @param {(코드: string) => string} 코드변환
 * @param {(나머지: string) => string} 나머지변환
 */
function 코드보호(텍스트, 코드변환, 나머지변환) {
  const 코드들 = []
  // 자리표시에 NUL 을 쓰므로 입력의 NUL 은 미리 걷어낸다 (글에 의미 있는 글자가 아니다)
  const 자리 = 텍스트.replace(/\u0000/g, '').replace(/`([^`\n]+)`/g, (_, 코드) => {
    코드들.push(코드변환(코드))
    return `\u0000${코드들.length - 1}\u0000`
  })
  return 나머지변환(자리).replace(/\u0000(\d+)\u0000/g, (_, i) => 코드들[Number(i)])
}

const 인라인HTML = (텍스트) => 코드보호(
  HTML이스케이프(텍스트),
  (코드) => `<code>${코드}</code>`,
  (나머지) => 나머지.replace(/\*\*([^*\n]+)\*\*/g, '<strong>$1</strong>'),
)
const 인라인텍스트 = (텍스트) => 코드보호(텍스트, (코드) => 코드, (나머지) => 나머지.replace(/\*\*([^*\n]+)\*\*/g, '$1'))

const 글머리식 = /^\s*[-*•]\s+(.+)$/
const 번호식 = /^\s*(\d{1,2})[.)]\s+(.+)$/
const 수평선식 = /^\s*([-*_])(\s*\1){2,}\s*$/ // "---" "* * *" 같은 구분선
const 펜스식 = /^\s*```/
/** 하위 목록·이어지는 줄로 볼 최소 추가 들여쓰기 */
const 하위들여씀 = 2

const 들여쓰기 = (줄) => /^\s*/.exec(줄)[0].replace(/\t/g, '    ').length

/**
 * 목록 표시가 붙은 줄이면 그 정보를, 아니면 null.
 * @returns {{ 종류: 'ul'|'ol', 번호?: number, 글: string } | null}
 */
function 목록표시(줄) {
  if (수평선식.test(줄)) return null
  const 글머리 = 글머리식.exec(줄)
  if (글머리) return { 종류: 'ul', 글: 글머리[1] }
  const 번호 = 번호식.exec(줄)
  if (번호) return { 종류: 'ol', 번호: Number(번호[1]), 글: 번호[2] }
  return null
}

/**
 * 줄들을 블록으로 쪼갠다. 목록 항목은 { 글: 줄[], 하위: 목록[] } 이고, 하위 목록의 항목은 { 글: 줄[] } 이다.
 * @returns {Array<
 *   | { 종류: 'p', 줄들: string[] }
 *   | { 종류: 'h', 글: string }
 *   | { 종류: 'hr' }
 *   | { 종류: 'code', 줄들: string[] }
 *   | { 종류: 'ul'|'ol', 시작: number, 들여씀: number, 항목: Array<{ 글: string[], 하위: Array<{ 종류: 'ul'|'ol', 시작: number, 들여씀: number, 항목: Array<{ 글: string[] }> }> }> }
 * >}
 */
function 블록파싱(텍스트) {
  const 줄들 = String(텍스트 ?? '').replace(/\r\n?/g, '\n').split('\n')
  const 블록들 = []
  let 문단 = null
  let 목록 = null // 열려 있는 최상위 목록. 빈 줄이 와도 바로 닫지 않는다 (모델은 항목 사이를 빈 줄로 띄우곤 한다)
  let 코드 = null
  // 바로 앞 번호 목록의 마지막 번호. 글머리 목록을 사이에 두고 이어지는 "2." 가 다시 1 부터 세어지지 않게.
  // 문단·제목·구분선·코드가 끼면 끊긴다
  let 직전번호 = 0

  const 문단닫기 = () => { if (문단) { 블록들.push(문단); 문단 = null; 직전번호 = 0 } }
  const 목록닫기 = () => {
    if (!목록) return
    if (목록.종류 === 'ol') 직전번호 = 목록.시작 + 목록.항목.length - 1
    목록 = null
  }
  const 모두닫기 = () => { 문단닫기(); 목록닫기() }

  for (const 원줄 of 줄들) {
    const 줄 = 원줄.trimEnd()

    // 코드 블록 안의 줄은 아무 규칙도 적용하지 않는다
    if (코드) {
      if (펜스식.test(줄)) { 블록들.push(코드); 코드 = null } else 코드.줄들.push(원줄)
      continue
    }
    if (펜스식.test(줄)) { 모두닫기(); 코드 = { 종류: 'code', 줄들: [] }; 직전번호 = 0; continue }

    if (!줄.trim()) { 문단닫기(); continue }

    const 깊이 = 들여쓰기(줄)
    const 표시 = 목록표시(줄)

    // 열린 목록보다 더 들여쓴 줄: 마지막 항목의 하위 목록이거나 이어지는 줄
    if (목록 && 깊이 >= 목록.들여씀 + 하위들여씀) {
      const 항목 = 목록.항목[목록.항목.length - 1]
      const 하위 = 항목.하위[항목.하위.length - 1]
      if (표시) {
        if (!하위 || 하위.종류 !== 표시.종류) 항목.하위.push({ 종류: 표시.종류, 시작: 표시.번호 ?? 1, 들여씀: 깊이, 항목: [] })
        항목.하위[항목.하위.length - 1].항목.push({ 글: [표시.글] })
      } else if (하위 && 깊이 >= 하위.들여씀 + 하위들여씀) {
        하위.항목[하위.항목.length - 1].글.push(줄.trim()) // 하위 항목보다 더 들여썼으면 그 하위 항목에
      } else {
        항목.글.push(줄.trim()) // 아니면 부모 항목에
      }
      continue
    }

    // 번호 목록은 1 로 시작하거나 번호 목록에 이어질 때만. "2026. 상반기에는…" 같은 문장을 목록으로 오해하지 않게
    const 번호이어짐 = 목록?.종류 === 'ol' || (!문단 && 직전번호 > 0)
    const 목록줄 = 표시 && (표시.종류 === 'ul' || 표시.번호 === 1 || 번호이어짐)

    if (목록줄) {
      문단닫기()
      if (목록 && 목록.종류 !== 표시.종류) 목록닫기()
      if (!목록) {
        const 시작 = 표시.종류 === 'ol' && 표시.번호 !== 1 ? 직전번호 + 1 : 1
        목록 = { 종류: 표시.종류, 시작, 들여씀: 깊이, 항목: [] }
        블록들.push(목록)
      }
      목록.항목.push({ 글: [표시.글], 하위: [] })
    } else if (수평선식.test(줄)) {
      모두닫기()
      블록들.push({ 종류: 'hr' }); 직전번호 = 0
    } else if (/^#{1,6}\s+(.+)$/.test(줄)) {
      모두닫기()
      블록들.push({ 종류: 'h', 글: /^#{1,6}\s+(.+)$/.exec(줄)[1] }); 직전번호 = 0
    } else {
      목록닫기()
      if (!문단) { 문단 = { 종류: 'p', 줄들: [] }; 직전번호 = 0 }
      문단.줄들.push(줄)
    }
  }
  if (코드) 블록들.push(코드) // 닫는 ``` 가 없으면 끝까지 코드로
  문단닫기(); 목록닫기()
  return 블록들
}

// ── HTML ────────────────────────────────────────────────────
const 시작속성 = (목록) => (목록.종류 === 'ol' && 목록.시작 > 1 ? ` start="${목록.시작}"` : '')
const 항목HTML = (항목) => {
  const 하위 = (항목.하위 ?? []).map(목록HTML).join('')
  return `<li>${항목.글.map(인라인HTML).join(' ')}${하위}</li>` // 이어지는 줄은 마크다운처럼 한 문단으로 잇는다
}
const 목록HTML = (목록) => `<${목록.종류}${시작속성(목록)}>${목록.항목.map(항목HTML).join('')}</${목록.종류}>`

/**
 * @param {string} 텍스트
 * @returns {string} HTML
 */
export function 마크다운HTML(텍스트) {
  return 블록파싱(텍스트).map((블록) => {
    switch (블록.종류) {
      case 'p': return `<p>${블록.줄들.map(인라인HTML).join('<br>')}</p>`
      case 'h': return `<h4>${인라인HTML(블록.글)}</h4>`
      case 'hr': return '<hr>'
      case 'code': return `<pre><code>${HTML이스케이프(블록.줄들.join('\n'))}</code></pre>`
      case 'ul': case 'ol': return 목록HTML(블록)
      default: return ''
    }
  }).join('')
}

// ── 일반 텍스트 ─────────────────────────────────────────────
/** 목록을 줄들로. 이어지는 줄과 하위 목록은 들여 써서 화면의 계층이 복사 글에도 남게 한다 */
function 목록텍스트(목록, 들여 = '') {
  return 목록.항목.flatMap((항목, i) => {
    const 머리 = 목록.종류 === 'ol' ? `${목록.시작 + i}. ` : '• '
    const [첫줄, ...나머지] = 항목.글.map(인라인텍스트)
    return [
      `${들여}${머리}${첫줄}`,
      ...나머지.map((줄) => `${들여}  ${줄}`),
      ...(항목.하위 ?? []).flatMap((하위) => 목록텍스트(하위, `${들여}  `)),
    ]
  })
}

/**
 * 공유용 일반 텍스트. 마크다운 기호를 걷어내 메신저·메모에 붙여 넣어도 깔끔하게 보인다.
 * 제목은 그대로 한 줄, 글머리는 "• ", 번호 목록은 화면과 같은 번호로, 굵게·코드는 기호만 벗긴다.
 * 구분선은 빈 줄, 코드 블록은 글자 그대로.
 * @param {string} 텍스트
 * @returns {string}
 */
export function 마크다운텍스트(텍스트) {
  return 블록파싱(텍스트).map((블록) => {
    switch (블록.종류) {
      case 'p': return 블록.줄들.map(인라인텍스트).join('\n')
      case 'h': return 인라인텍스트(블록.글)
      case 'hr': return ''
      case 'code': return 블록.줄들.join('\n')
      case 'ul': case 'ol': return 목록텍스트(블록).join('\n')
      default: return ''
    }
  }).filter(Boolean).join('\n\n')
}
