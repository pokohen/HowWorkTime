import { 월공휴일 } from '../../worktime/utils/holidays'
import { 날짜키, 근무일여부, 날짜더하기 } from '../../worktime/utils/workDays'
import { 날짜요일표시 } from '../../shared/utils/timeFormat'

/** 연휴로 볼 최소 연속 휴일 수 (주말 2일은 연휴가 아니다) */
const 연휴최소일수 = 3

const 쉬는날여부 = (날짜) => !근무일여부(날짜)

/** 구간이 달 경계를 넘어갈 수 있어 앞뒤로 이만큼 더 본다. 징검다리 포함 가장 긴 연휴(열흘 남짓)보다 크게 */
const 탐색여유일 = 10

/**
 * 어떤 달(또는 그달부터 몇 달)의 연휴(주말+공휴일이 3일 이상 이어지는 구간)와 징검다리(연휴 사이에 낀 평일 하루) 를 찾는다.
 * 달 경계에 걸친 연휴도 잡기 위해 앞뒤로 며칠 더 보고, 범위 안에 하루라도 걸치는 구간만 돌려준다.
 * 두 달을 따로 찾아 합치면 경계에 걸친 구간이 한쪽에서 잘릴 수 있으므로, 이어진 달은 개월수로 한 번에 찾는다.
 *
 * @param {number} 연도
 * @param {number} 월
 * @param {(날짜: Date) => boolean} [쉬는날]
 * @param {number} [개월수] 월부터 몇 달을 볼지 (기본 1)
 * @returns {Array<{ 시작: string, 끝: string, 일수: number, 공휴일: string[], 징검다리: string[] }>}
 */
export function 연휴찾기(연도, 월, 쉬는날 = 쉬는날여부, 개월수 = 1) {
  const 공휴일이름 = new Map(
    Array.from({ length: 개월수 + 2 }, (_, i) => 월 - 1 + i).flatMap((m) => {
      const d = new Date(연도, m - 1, 1)
      return 월공휴일(d.getFullYear(), d.getMonth() + 1).map((항목) => [항목.날짜, 항목.이름])
    }),
  )
  const 월초 = new Date(연도, 월 - 1, 1)
  const 월말 = new Date(연도, 월 - 1 + 개월수, 0) // 마지막 달의 말일
  const 시작 = 날짜더하기(월초, -탐색여유일)
  const 끝 = 날짜더하기(월말, 탐색여유일)

  // 1) 연속된 쉬는 날 덩어리를 모은다
  const 덩어리들 = []
  let 현재 = null
  for (let d = new Date(시작); d <= 끝; d = 날짜더하기(d, 1)) {
    const 오늘 = new Date(d)
    if (쉬는날(오늘)) {
      if (!현재) { 현재 = []; 덩어리들.push(현재) }
      현재.push(오늘)
    } else {
      현재 = null
    }
  }

  // 2) 후보 = 덩어리 하나 + 평일 하루(징검다리)만 사이에 둔 이웃 덩어리 둘을 합친 것.
  //    탐욕적으로 이어 붙이면 어느 쪽에 징검다리를 쓰느냐에 따라 더 긴 연휴를 놓치므로, 가능한 조합을 모두 낸다
  //    (예: 토 일 [월] 화 [수] 목 금 토 일 → 토~화 · 화~일 · 목~일 셋 다 후보)
  const 후보들 = 덩어리들.map((덩어리) => 덩어리.map((날짜) => ({ 날짜, 징검다리: false })))
  for (let i = 0; i + 1 < 덩어리들.length; i++) {
    const 앞 = 덩어리들[i]
    const 뒤 = 덩어리들[i + 1]
    const 사이 = 날짜더하기(앞[앞.length - 1], 1)
    if (날짜키(날짜더하기(사이, 1)) !== 날짜키(뒤[0])) continue // 사이에 평일이 하루보다 많다
    후보들.push([
      ...앞.map((날짜) => ({ 날짜, 징검다리: false })),
      { 날짜: 사이, 징검다리: true },
      ...뒤.map((날짜) => ({ 날짜, 징검다리: false })),
    ])
  }

  return 후보들
    .map((날들) => {
      const 쉬는날들 = 날들.filter((n) => !n.징검다리)
      return {
        시작: 날짜키(날들[0].날짜),
        끝: 날짜키(날들[날들.length - 1].날짜),
        일수: 날들.length,
        공휴일: [...new Set(쉬는날들.map((n) => 공휴일이름.get(날짜키(n.날짜))).filter(Boolean))],
        징검다리: 날들.filter((n) => n.징검다리).map((n) => 날짜키(n.날짜)),
        _끝날짜: 날들[날들.length - 1].날짜,
        _시작날짜: 날들[0].날짜,
      }
    })
    // 범위 안에 하루라도 걸치고, 징검다리를 뺀 쉬는 날이 3일 이상인 것만
    .filter((구간) => 구간._끝날짜 >= 월초 && 구간._시작날짜 <= 월말 && 구간.일수 - 구간.징검다리.length >= 연휴최소일수)
    .map(({ _끝날짜, _시작날짜, ...구간 }) => 구간)
    .sort((a, b) => a.시작.localeCompare(b.시작) || a.끝.localeCompare(b.끝))
}


/**
 * 모델에 보낼 이력. 실패·빈 응답은 빼고 같은 역할이 이어지면 합친 뒤, 최근 것만 남기고
 * 맨 앞이 user 가 되게 다듬는다 (Anthropic 은 첫 메시지가 user 가 아니면 거부한다).
 * @param {Array<{ 역할: 'user'|'assistant', 내용: string, 오류?: string }>} 메시지들
 * @param {number} 최대 - 남길 메시지 수 상한
 */
export function 이력만들기(메시지들, 최대 = Infinity) {
  const 결과 = []
  for (const m of 메시지들) {
    if (m.역할 === 'assistant' && (!m.내용 || m.오류)) continue
    if (!m.내용) continue
    const 마지막 = 결과[결과.length - 1]
    if (마지막 && 마지막.역할 === m.역할) 마지막.내용 += `\n\n${m.내용}`
    else 결과.push({ 역할: m.역할, 내용: m.내용 })
  }
  const 최근 = 결과.slice(-최대)
  while (최근.length && 최근[0].역할 !== 'user') 최근.shift()
  return 최근
}

function 연휴한줄(구간) {
  const 기간 = `${날짜요일표시(구간.시작)}~${날짜요일표시(구간.끝)} ${구간.일수}일`
  const 이름 = 구간.공휴일.length ? ` · ${구간.공휴일.join(', ')}` : ''
  const 다리 = 구간.징검다리.length ? ` · ${구간.징검다리.map(날짜요일표시).join(', ')}에 연차를 쓰면 이어짐` : ''
  return `- ${기간}${이름}${다리}`
}

/**
 * 앱이 이미 아는 것을 모델에게 알려 주는 시스템 프롬프트.
 * 순수 함수라 테스트에서 그대로 확인할 수 있다. 날짜·숫자는 호출 쪽(useAssistant)이 채운다.
 *
 * @param {{
 *   오늘표시: string, 이번달표시: string, 다음달표시: string,
 *   이번달공휴일: Array<{ 날짜: string, 이름: string }>, 다음달공휴일: Array<{ 날짜: string, 이름: string }>,
 *   연휴: ReturnType<typeof 연휴찾기>,
 *   보는달이오늘달?: boolean, 지난달보는중?: boolean, 보는달표시?: string,
 *   남은근무일: number|null, 출근남은일: number|null, 연차일수: number,
 *   남은연차목록?: Array<{ 연도: number, 남은: string }>, 재택안내?: string, 급여주여부?: boolean,
 * }} 컨텍스트
 */
export function 시스템프롬프트(컨텍스트) {
  const {
    오늘표시, 이번달표시, 다음달표시, 이번달공휴일 = [], 다음달공휴일 = [], 연휴 = [],
    보는달이오늘달 = true, 지난달보는중 = false, 보는달표시 = '',
    남은근무일, 출근남은일, 연차일수 = 0, 남은연차목록 = [], 재택안내 = '', 급여주여부 = false,
  } = 컨텍스트

  const 공휴일줄 = (목록) => (목록.length ? 목록.map((h) => `${날짜요일표시(h.날짜)} ${h.이름}`).join(', ') : '없음')

  return [
    '당신은 한국 직장인의 "쉬는 날 플래너"입니다. 휴가에 뭘 할지, 주말을 어떻게 보낼지, 여행 일정을 어떻게 짤지 함께 고민해 줍니다.',
    '',
    '## 지금 상황 (근무시간 계산기 앱이 알려 주는 정보)',
    `- 오늘: ${오늘표시}${급여주여부 ? ' (이번 주 급여일)' : ''}${재택안내 ? ` · ${재택안내}` : ''}`,
    // 앱에서 다른 달을 보고 있으면 아래 숫자는 그 달 기준이다. '이번 달'이라고 뭉뚱그리면 모델이 오늘과 어긋나게 읽는다
    ...(보는달이오늘달 ? [] : 지난달보는중
      ? [`- 사용자가 앱에서 보고 있는 달은 이미 지난 ${보는달표시}. 계획은 앞날 얘기이므로 아래 공휴일·연휴는 오늘이 속한 ${이번달표시}부터`]
      : [`- 사용자가 지금 앱에서 보고 있는 달: ${이번달표시} (오늘이 속한 달이 아님). 아래 공휴일·근무일 숫자는 이 달 기준`]),
    `- ${이번달표시} 공휴일: ${공휴일줄(이번달공휴일)}`,
    `- ${다음달표시} 공휴일: ${공휴일줄(다음달공휴일)}`,
    ...(남은근무일 == null ? [] : [`- ${이번달표시} 남은 근무일 ${남은근무일}일, 그중 실제 출근 예정 ${출근남은일}일${연차일수 > 0 ? `, 이미 지정한 연차 ${연차일수}일` : ''}`]),
    ...남은연차목록.map(({ 연도, 남은 }) => `- ${연도}년 남은 연차: ${남은} (하루 8시간 기준 · 사용자가 직접 적은 값. 그 해 날짜에는 이 안에서 연차·반차를 제안합니다)`),
    '- 연휴 후보 (주말·공휴일이 이어지는 구간):',
    ...(연휴.length ? 연휴.map(연휴한줄) : ['- 없음']),
    '',
    '## 대화 방식',
    '- 한국어로, 친근하지만 간결하게. 긴 서론 없이 바로 제안합니다.',
    `- 날짜를 말할 때는 위 정보에 근거하고, 모르는 것(예: ${남은연차목록.length === 0 ? '사용자의 남은 연차 총량, ' : ''}예산, 동행)은 짐작하지 말고 한 번에 한두 가지만 물어봅니다.`,
    '- 제안은 2~4개로 압축하고, 각 제안에 왜 그 시기가 좋은지 한 줄 근거를 붙입니다.',
    '- 여행 일정은 날짜별로 굵은 제목 + 짧은 목록으로 정리합니다.',
    '- 마크다운은 굵게, 목록, 짧은 제목 정도만 가볍게 씁니다. 표나 코드 블록은 쓰지 않습니다.',
    '- 실시간 정보(날씨, 가격, 영업시간, 예약 가능 여부)는 확인이 필요하다고 분명히 말합니다.',
  ].join('\n')
}
