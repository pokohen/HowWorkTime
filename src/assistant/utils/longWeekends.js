/**
 * 연휴 후보 찾기. 주말·공휴일 덩어리와, 평일 하루(징검다리)로 이어지는 이웃 덩어리를 합친 조합을 모두 낸다.
 * 순수 함수라 쉬는 날 판정을 바꿔 끼워 테스트할 수 있다.
 */
import { 월공휴일 } from '../../worktime/utils/holidays'
import { 날짜키, 근무일여부, 날짜더하기 } from '../../worktime/utils/workDays'

/** 연휴로 볼 최소 연속 휴일 수 (주말 2일은 연휴가 아니다) */
const 연휴최소일수 = 3

const 쉬는날여부 = (날짜) => !근무일여부(날짜)

/** 구간이 달 경계를 넘어갈 수 있어 앞뒤로 이만큼 더 본다. 징검다리 포함 가장 긴 연휴(열흘 남짓)보다 넉넉히 */
const 탐색여유일 = 20

/**
 * 어떤 달(또는 그달부터 몇 달)의 연휴(주말+공휴일이 3일 이상 이어지는 구간)와 징검다리(연휴 사이에 낀 평일 하루) 를 찾는다.
 * 달 경계에 걸친 연휴도 잡기 위해 앞뒤로 며칠 더 보고, 범위 안에 하루라도 걸치는 구간만 돌려준다.
 * 이어진 달은 개월수로 한 번에 찾는 편이 간단하다. 따로 찾아 합칠 때는 같은 연휴가 양쪽에 나올 수 있으므로
 * 날짜가 겹치는 구간을 같은 것으로 보고 하나만 남긴다 (앞뒤 여유 덕분에 보통은 모양도 같다).
 *
 * @param {number} 연도
 * @param {number} 월
 * @param {(날짜: Date) => boolean} [쉬는날]
 * @param {number} [개월수] 월부터 몇 달을 볼지 (기본 1)
 * @returns {Array<{ 시작: string, 끝: string, 일수: number, 공휴일: string[], 징검다리: string[] }>}
 */
export function 연휴찾기(연도, 월, 쉬는날 = 쉬는날여부, 개월수 = 1) {
  const 공휴일이름 = new Map(
    Array.from({ length: 개월수 + 2 }, (_, i) => 월 - 1 + i).flatMap((m) => {
      const d = new Date(연도, m - 1, 1)
      return 월공휴일(d.getFullYear(), d.getMonth() + 1).map((항목) => [항목.날짜, 항목.이름])
    }),
  )
  const 월초 = new Date(연도, 월 - 1, 1)
  const 월말 = new Date(연도, 월 - 1 + 개월수, 0) // 마지막 달의 말일
  const 시작 = 날짜더하기(월초, -탐색여유일)
  const 끝 = 날짜더하기(월말, 탐색여유일)

  // 1) 연속된 쉬는 날 덩어리를 모은다
  const 덩어리들 = []
  let 현재 = null
  for (let d = new Date(시작); d <= 끝; d = 날짜더하기(d, 1)) {
    const 오늘 = new Date(d)
    if (쉬는날(오늘)) {
      if (!현재) { 현재 = []; 덩어리들.push(현재) }
      현재.push(오늘)
    } else {
      현재 = null
    }
  }

  // 2) 후보 = 덩어리 하나 + 평일 하루(징검다리)만 사이에 둔 이웃 덩어리 둘을 합친 것.
  //    탐욕적으로 이어 붙이면 어느 쪽에 징검다리를 쓰느냐에 따라 더 긴 연휴를 놓치므로, 가능한 조합을 모두 낸다
  //    (예: 토 일 [월] 화 [수] 목 금 토 일 → 토~화 · 화~일 · 목~일 셋 다 후보)
  const 후보들 = 덩어리들.map((덩어리) => 덩어리.map((날짜) => ({ 날짜, 징검다리: false })))
  for (let i = 0; i + 1 < 덩어리들.length; i++) {
    const 앞 = 덩어리들[i]
    const 뒤 = 덩어리들[i + 1]
    const 사이 = 날짜더하기(앞[앞.length - 1], 1)
    if (날짜키(날짜더하기(사이, 1)) !== 날짜키(뒤[0])) continue // 사이에 평일이 하루보다 많다
    후보들.push([
      ...앞.map((날짜) => ({ 날짜, 징검다리: false })),
      { 날짜: 사이, 징검다리: true },
      ...뒤.map((날짜) => ({ 날짜, 징검다리: false })),
    ])
  }

  return 후보들
    .map((날들) => {
      const 쉬는날들 = 날들.filter((n) => !n.징검다리)
      return {
        시작: 날짜키(날들[0].날짜),
        끝: 날짜키(날들[날들.length - 1].날짜),
        일수: 날들.length,
        공휴일: [...new Set(쉬는날들.map((n) => 공휴일이름.get(날짜키(n.날짜))).filter(Boolean))],
        징검다리: 날들.filter((n) => n.징검다리).map((n) => 날짜키(n.날짜)),
        _끝날짜: 날들[날들.length - 1].날짜,
        _시작날짜: 날들[0].날짜,
      }
    })
    // 범위 안에 하루라도 걸치고, 징검다리를 뺀 쉬는 날이 3일 이상인 것만
    .filter((구간) => 구간._끝날짜 >= 월초 && 구간._시작날짜 <= 월말 && 구간.일수 - 구간.징검다리.length >= 연휴최소일수)
    .map(({ _끝날짜, _시작날짜, ...구간 }) => 구간)
    .sort((a, b) => a.시작.localeCompare(b.시작) || a.끝.localeCompare(b.끝))
}
