import { 저장이벤트감시, 다른창저장감시, 공간생긴변경 } from '../utils/storage'

/** 단조 시계(ms). 시스템 시계가 바뀌어도 거꾸로 가지 않는다 */
const 지금 = () => (globalThis.performance?.now?.() ?? Date.now())

/**
 * 저장소에 쓰지 못한 것을 다시 써 보는 규칙 (대화·설정이 함께 쓴다).
 * - 다른 창이 무언가를 지우거나 줄이면(통째 비움 포함) 공간이 생겼으니 바로 (다음 틈에)
 * - 다른 창이 이 키를 늘렸으면 쓰기에 실패한 뒤 간격이 지나서 한 번 (버리지 않고 미룬다. 자주 쓰는 창 때문에 되풀이하지 않게)
 * - 이 창을 떠날 때(떠날때다시쓰기) 마지막으로
 * 이벤트가 담은 값이 이미 지금 저장소 값과 다르면(늦게 닿음) 그 이벤트의 '줄었음'은 믿지 않는다.
 * 이 키(와 통째 비움)의 다른 창 저장은 여기서 받아, 부르는 모듈의 합치기(값, e)를 먼저 부른 뒤 그 상태로 판단한다
 * (순서가 구조로 보장된다. 합치기가 예외를 내면 기록하고 판단은 이어서 한다).
 * 합치지 못한 남의 값을 지킬지는 여기서 정하지 않는다: 부르는 모듈의 보통 저장도 다음 변경·떠남 때 그 위에 쓰므로,
 * 재시도만 막으면 늦어질 뿐 지켜지지 않는다 (그 정책은 모듈의 저장이 한 곳에서 정한다).
 * 통째 비움 뒤 이 키에 값이 있으면 늦게 닿은 것으로 본다 (이 창이 그 뒤 쓴 경우도 그렇게 봐 간격만큼 늦어질 수 있다). 다른 키는 줄였을 때만 받는다.
 * 스스로는 되풀이하지 않는다: 다시 쓰기가 또 실패하면 다음 바깥 일을 기다린다
 * @param {(fn: () => void) => void} 정리등록
 * @param {{ 키: string, 합치기: (값: string|null, e: StorageEvent) => void, 쓸것있음: () => boolean, 다시쓰기: () => void, 간격?: number, 떠날때다시쓰기?: boolean }} 옵션
 *   합치기: 다른 창이 이 키를 바꿨을 때 그 값(지금 저장소 값)을 합친다
 * @returns {{ 실패함: () => void, 거둠: () => void }} 실패함: 쓰기에 실패했을 때. 거둠: 지금 쓰니 미뤄 둔 재시도를 거둔다
 */
export function 쓰기재시도(정리등록, { 키, 합치기, 쓸것있음, 다시쓰기, 간격 = 5_000, 떠날때다시쓰기 = true }) {
  let 실패때 = -Infinity
  let 타이머 = null
  let 바로 = false
  let 멈춤 = false
  const 거둠 = () => {
    clearTimeout(타이머)
    타이머 = null
    바로 = false
  }
  function 예약(기다림) {
    if (타이머) {
      if (바로 || 기다림 > 0) return // 이미 바로 하거나, 같은 간격으로 미뤄 두었다
      거둠() // 미뤄 둔 것을 바로로 앞당긴다
    }
    바로 = 기다림 === 0
    타이머 = setTimeout(() => {
      타이머 = null
      바로 = false
      if (!멈춤 && 쓸것있음()) 다시쓰기()
    }, 기다림)
  }
  정리등록(() => { 멈춤 = true; 거둠() })
  /** 이 키·통째 비움 이벤트를 합친 뒤 판단한다. 값: 지금 저장소 값 (다시 읽지 않는다) */
  function 이키판단(값, e) {
    if (멈춤 || !쓸것있음()) return
    // 늦게 닿음: 이벤트 뒤 다른 창이 다시 써 지금 값이 이벤트가 말한 값과 다르다
    // (이 키: 이벤트 값과 다름, 지움 뒤 다시 채움 포함 / 통째 비움: 비웠다는데 이 키에 값이 있다)
    const 늦게닿음 = e.key === 키 ? (e.newValue ?? null) !== 값 : 값 != null
    if (공간생긴변경(e) && !늦게닿음) return 예약(0)
    예약(Math.max(0, 실패때 + 간격 - 지금()))
  }
  정리등록(다른창저장감시(키, (값, e) => {
    try {
      합치기(값, e)
    } catch (예외) {
      console.error('[저장] 다른 창의 저장을 합치지 못함', 예외) // 판단은 이어서 한다
    }
    이키판단(값, e)
  }))
  // 다른 키는 지우거나 줄였을 때만 (공간이 생김). 이 키·통째 비움은 위에서 다룬다
  정리등록(저장이벤트감시((e) => {
    if (e.key === 키 || e.key === null || !공간생긴변경(e)) return
    if (!멈춤 && 쓸것있음()) 예약(0)
  }))
  if (떠날때다시쓰기 && typeof window !== 'undefined') {
    const 떠날때 = () => { if (쓸것있음()) 다시쓰기() }
    window.addEventListener('pagehide', 떠날때)
    정리등록(() => window.removeEventListener('pagehide', 떠날때))
  }
  return { 실패함: () => { 실패때 = 지금() }, 거둠 }
}
