import { describe, it, expect } from 'vitest'
import { 소정근로일수, 남은근무일수, 남은금요일수, 급여일조회 } from '../src/utils/workDays'

// 2026년 9월: 30일, 추석 연휴 24(목)~26(토). 평일 22일 − 공휴일 평일 2일 = 20일
// 2026년 10월: 개천절 3(토)→대체 5(월), 한글날 9(금). 평일 22일 − 2일 = 20일
const 오늘 = new Date(2026, 8, 28) // 9/28 월

describe('소정근로일수', () => {
  it('주말과 공휴일을 제외한다', () => {
    expect(소정근로일수(2026, 9)).toBe(20)
    expect(소정근로일수(2026, 10)).toBe(20)
  })
  it('입사일부터 센다 (입사일 포함)', () => {
    expect(소정근로일수(2026, 9, 15)).toBe(10)
    expect(소정근로일수(2026, 9, 28)).toBe(3) // 28, 29, 30
  })
  it('시작일이 범위를 벗어나면 보정', () => {
    expect(소정근로일수(2026, 9, 0)).toBe(20)
    expect(소정근로일수(2026, 9, 99)).toBe(1) // 30일 하루
  })
})

describe('남은근무일수', () => {
  it('오늘을 제외하고 내일부터 월말까지', () => {
    expect(남은근무일수(2026, 9, 1, 오늘)).toBe(2) // 29, 30
  })
  it('지난 달은 0, 다음 달은 전체', () => {
    expect(남은근무일수(2026, 8, 1, 오늘)).toBe(0)
    expect(남은근무일수(2026, 10, 1, 오늘)).toBe(20)
  })
  it('입사일이 내일 이후면 입사일부터', () => {
    expect(남은근무일수(2026, 9, 30, 오늘)).toBe(1)
  })
  it('월말이면 0', () => {
    expect(남은근무일수(2026, 9, 1, new Date(2026, 8, 30))).toBe(0)
  })
})

describe('남은금요일수', () => {
  it('공휴일인 금요일은 제외', () => {
    // 10월 금요일: 2, 9(한글날), 16, 23, 30 → 4
    expect(남은금요일수(2026, 10, 1, 오늘)).toBe(4)
  })
  it('이번 달 남은 금요일이 없으면 0', () => {
    expect(남은금요일수(2026, 9, 1, 오늘)).toBe(0)
  })
  it('오늘이 금요일이면 오늘은 제외', () => {
    expect(남은금요일수(2026, 10, 1, new Date(2026, 9, 2))).toBe(3)
  })
})

describe('급여일조회', () => {
  it('기준일이 평일이면 그대로', () => {
    expect(급여일조회(2026, 8).getDate()).toBe(25) // 화
  })
  it('주말이면 직전 금요일', () => {
    expect(급여일조회(2026, 7).getDate()).toBe(24) // 25 토 → 24 금
  })
  it('공휴일이면 직전 평일', () => {
    expect(급여일조회(2026, 9).getDate()).toBe(23) // 25 추석 → 24 추석 → 23 수
  })
})
