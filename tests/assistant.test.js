import { describe, it, expect } from 'vitest'
import { 연휴찾기 } from '../src/assistant/utils/longWeekends'
import { 시스템프롬프트 } from '../src/assistant/utils/systemPrompt'
import { 이력만들기 } from '../src/assistant/utils/history'
import { 날짜키 } from '../src/worktime/utils/workDays'

// 공휴일은 tests/setup.js 가 2026년 픽스처로 고정한다
describe('연휴찾기', () => {
  it('설날처럼 주말과 이어지는 공휴일을 한 구간으로 묶는다', () => {
    const 연휴 = 연휴찾기(2026, 2)
    const 설날 = 연휴.find((구간) => 구간.공휴일.includes('설날'))
    expect(설날).toBeDefined()
    // 2/14(토) 2/15(일) 2/16~18(설날) = 5일
    expect(설날.시작).toBe('2026-02-14')
    expect(설날.끝).toBe('2026-02-18')
    expect(설날.일수).toBe(5)
    expect(설날.징검다리).toEqual([])
  })

  it('연휴 사이에 낀 평일 하루는 징검다리로 표시한다', () => {
    const 연휴 = 연휴찾기(2026, 5)
    // 5/1(금 노동절) 5/2(토) 5/3(일) [5/4 월] 5/5(화 어린이날)
    const 어린이날 = 연휴.find((구간) => 구간.공휴일.includes('어린이날'))
    expect(어린이날).toBeDefined()
    expect(어린이날.시작).toBe('2026-05-01')
    expect(어린이날.끝).toBe('2026-05-05')
    expect(어린이날.징검다리).toEqual(['2026-05-04'])
    expect(어린이날.일수).toBe(5)
  })

  it('달 경계에 걸친 연휴도 양쪽 달에서 보인다', () => {
    // 2/28(토) 3/1(일 삼일절) 3/2(월 대체공휴일)
    const 삼일절2월 = 연휴찾기(2026, 2).find((구간) => 구간.공휴일.includes('삼일절'))
    const 삼일절3월 = 연휴찾기(2026, 3).find((구간) => 구간.공휴일.includes('삼일절'))
    expect(삼일절2월?.시작).toBe('2026-02-28')
    expect(삼일절3월?.끝).toBe('2026-03-02')
    expect(삼일절3월.일수).toBe(3)
  })

  it('징검다리는 구간당 하루만 — 쉬는날·평일이 번갈아 와도 긴 연휴로 뭉치지 않는다', () => {
    // 토 일 [월] 화 [수] 목 [금] 토 일 꼴로 쉬는 날을 만든다 (2026-06 기준, 6/6 토 ~ 6/14 일)
    const 쉬는날집합 = new Set(['2026-06-06', '2026-06-07', '2026-06-09', '2026-06-11', '2026-06-13', '2026-06-14'])
    const 쉬는날 = (날짜) => 쉬는날집합.has(날짜키(날짜))
    const 구간들 = 연휴찾기(2026, 6, 쉬는날)
    expect(구간들.map((g) => [g.시작, g.끝, g.징검다리])).toEqual([
      ['2026-06-06', '2026-06-09', ['2026-06-08']],
      ['2026-06-11', '2026-06-14', ['2026-06-12']],
    ])
  })

  it('앞 구간이 징검다리를 써도 연휴가 못 되면, 징검다리 뒤부터 다시 시작해 뒤쪽 연휴를 놓치지 않는다', () => {
    // 화(공휴일) [수] 목(공휴일) [금] 토 일 → 목~일 4일(금 연차) 이 나와야 한다
    const 쉬는날집합 = new Set(['2026-06-02', '2026-06-04', '2026-06-06', '2026-06-07'])
    const 쉬는날 = (날짜) => 쉬는날집합.has(날짜키(날짜))
    const 구간들 = 연휴찾기(2026, 6, 쉬는날)
    expect(구간들.map((g) => [g.시작, g.끝, g.징검다리])).toEqual([['2026-06-04', '2026-06-07', ['2026-06-05']]])
  })

  it('앞 덩어리가 혼자서도 연휴일 때도, 징검다리를 다른 쪽에 쓴 더 긴 연휴를 함께 낸다', () => {
    // 토 일 [월] 화(공휴일) [수] 목(공휴일) 금 토 일 → 토~화(월 연차) · 화~일(수 연차, 6일) · 목~일(연차 없이 4일)
    const 쉬는날집합 = new Set(['2026-06-06', '2026-06-07', '2026-06-09', '2026-06-11', '2026-06-12', '2026-06-13', '2026-06-14'])
    const 쉬는날 = (날짜) => 쉬는날집합.has(날짜키(날짜))
    expect(연휴찾기(2026, 6, 쉬는날).map((g) => [g.시작, g.끝, g.일수, g.징검다리])).toEqual([
      ['2026-06-06', '2026-06-09', 4, ['2026-06-08']],
      ['2026-06-09', '2026-06-14', 6, ['2026-06-10']],
      ['2026-06-11', '2026-06-14', 4, []],
    ])
  })

  it('두 달을 한 번에 찾으면 경계에 걸친 구간이 한 번만, 잘리지 않고 나온다', () => {
    // 2/28(토) 3/1(일 삼일절) 3/2(월 대체공휴일) 가 2월·3월 경계에 걸친다
    const 두달 = 연휴찾기(2026, 2, undefined, 2)
    const 삼일절 = 두달.filter((구간) => 구간.공휴일.includes('삼일절'))
    expect(삼일절).toHaveLength(1)
    expect(삼일절[0]).toMatchObject({ 시작: '2026-02-28', 끝: '2026-03-02', 일수: 3 })
    // 2월의 설날 연휴도 같은 결과에 들어 있다 (두 달 범위)
    expect(두달.some((구간) => 구간.공휴일.includes('설날'))).toBe(true)
    // 한 달만 찾을 때와 범위가 같은 달에선 결과가 같다
    expect(연휴찾기(2026, 2)).toEqual(두달.filter((구간) => 구간.시작 <= '2026-02-28'))
  })

  it('평범한 주말(2일)은 연휴로 치지 않는다', () => {
    for (const 구간 of 연휴찾기(2026, 11)) {
      expect(구간.일수).toBeGreaterThanOrEqual(3)
    }
  })
})

describe('시스템프롬프트', () => {
  const 기본 = {
    오늘표시: '2026년 2월 10일 화요일',
    이번달표시: '2026년 2월',
    다음달표시: '2026년 3월',
    이번달공휴일: [{ 날짜: '2026-02-16', 이름: '설날' }],
    다음달공휴일: [],
    연휴: 연휴찾기(2026, 2),
    남은근무일: 10,
    출근남은일: 8,
    연차일수: 1,
    재택안내: '내일은 재택근무',
    급여주여부: false,
  }

  it('앱이 아는 날짜·공휴일·연휴·근무일 정보를 담는다', () => {
    const 글 = 시스템프롬프트(기본)
    expect(글).toContain('2026년 2월 10일 화요일')
    expect(글).toContain('2월 16일 (월) 설날')
    expect(글).toContain('2026년 3월 공휴일: 없음')
    expect(글).toContain('2026년 2월 남은 공휴일: 2월 16일 (월) 설날')
    expect(글).toContain('2026년 2월 남은 근무일 10일')
    expect(글).not.toContain('보고 있는 달')
    expect(글).toContain('출근 예정 8일')
    expect(글).toContain('연차 1일')
    expect(글).toContain('내일은 재택근무')
    expect(글).toMatch(/2월 14일 \(토\)~2월 18일 \(수\) 5일/)
  })

  it('연휴가 없으면 없음으로, 급여주면 표시한다', () => {
    const 글 = 시스템프롬프트({ ...기본, 연휴: [], 급여주여부: true, 연차일수: 0, 재택안내: '' })
    expect(글).toContain('- 없음')
    expect(글).toContain('(이번 주 급여일)')
    expect(글).not.toContain('이미 지정한 연차')
  })

  it('다른 달을 보고 있으면 숫자가 그 달 기준임을 밝히고, 지난 달이면 오늘 달부터라고 밝힌다', () => {
    const 글 = 시스템프롬프트({ ...기본, 보는달이오늘달: false })
    expect(글).toContain('보고 있는 달: 2026년 2월')
    const 과거 = 시스템프롬프트({ ...기본, 보는달이오늘달: false, 지난달보는중: true, 보는달표시: '2025년 12월', 남은근무일: null, 출근남은일: null })
    expect(과거).toContain('이미 지난 2025년 12월')
    expect(과거).toContain('2026년 2월부터')
    expect(과거).not.toContain('남은 근무일')
  })

  it('남은 연차를 적어 두면 알려 주고, 모르면 물어보라는 예시에 남겨 둔다', () => {
    const 모름 = 시스템프롬프트({ ...기본, 남은연차목록: [] })
    expect(모름).not.toContain('남은 연차:')
    expect(모름).toContain('남은 연차 총량')
    const 앎 = 시스템프롬프트({ ...기본, 남은연차목록: [{ 연도: 2026, 남은: '7일 4시간' }, { 연도: 2027, 남은: '15일' }] })
    expect(앎).toContain('2026년 남은 연차: 7일 4시간')
    expect(앎).toContain('2027년 남은 연차: 15일')
    expect(앎).not.toContain('남은 연차 총량')
  })
})

describe('이력만들기', () => {
  const 쌍 = (n) => Array.from({ length: n }, (_, i) => [
    { 역할: 'user', 내용: `질문 ${i}` },
    { 역할: 'assistant', 내용: `답 ${i}` },
  ]).flat()

  it('실패·빈 응답은 빼고 같은 역할이 이어지면 합친다', () => {
    const 결과 = 이력만들기([
      { 역할: 'user', 내용: '하나' },
      { 역할: 'assistant', 내용: '', 오류: '실패' },
      { 역할: 'user', 내용: '둘' },
      { 역할: 'assistant', 내용: '' },
      { 역할: 'assistant', 내용: '답' },
    ])
    expect(결과).toEqual([{ 역할: 'user', 내용: '하나\n\n둘' }, { 역할: 'assistant', 내용: '답' }])
  })

  it('상한으로 자른 뒤에도 맨 앞은 user 다', () => {
    const 결과 = 이력만들기([...쌍(20), { 역할: 'user', 내용: '마지막' }], 40)
    expect(결과).toHaveLength(39)
    expect(결과[0]).toEqual({ 역할: 'user', 내용: '질문 1' })
    expect(결과.at(-1)).toEqual({ 역할: 'user', 내용: '마지막' })
  })

  it('맨 앞의 응답은 버린다', () => {
    expect(이력만들기([{ 역할: 'assistant', 내용: '인사' }, { 역할: 'user', 내용: '질문' }])).toEqual([{ 역할: 'user', 내용: '질문' }])
  })
})
